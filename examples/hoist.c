
#include "5510drv.h"

// Подъёмно-опускной механизм (лифт) №2 на стенде.
//
// Сценарий:
//   1. ждём нажатия кнопки Stand_by;
//   2. запускаем второй мотор - груз на нитке едет ВВЕРХ;
//   3. как только груз дошёл до верхнего датчика Place_2_1 - останавливаем мотор,
//      меняем направление (знак скорости) и опускаем груз вниз;
//   4. на нижнем датчике Place_2_3 мотор останавливается, программа завершается.
//
// Привод лифта - аналоговый мотор Analog_Motor_2 (выход №1 модуля ADAM-5024, слот 2):
//   Set5024(&v, 1, ...) записывает скорость; знак задаёт направление:
//     v > 0 - мотор наматывает нитку (груз вверх),
//     v < 0 - сматывает (груз вниз),
//     v = 0 - стоп.
// Датчики наличия Place_2_1 / Place_2_2 / Place_2_3 выдают 1, когда груз стоит
// напротив них (иначе 0). Груз изначально внизу - у датчика Place_2_3.
//
// Используются только стандартные функции драйвера: Set5050, Get5050, Set5024,
// Get5017, printf, ADAMdelay.

void main()
{
        //Слоты модулей
        unsigned char _5050_0 = 0;
        unsigned char _5050_1 = 1;              //ADAM-5050 в 1-ом слоте
        unsigned char _5024 = 2;                //ADAM-5024 во 2-ом слоте

        //Каналы цифровых устройств
        unsigned char Stand_by_CH = 4;          //кнопка Stand_by (вход)
        unsigned char Place_2_1_CH = 10;        //верхний датчик положения груза
        unsigned char Place_2_3_CH = 10;        //нижний датчик положения груза

        //Канал аналогового выхода, к которому подключён 2-ой мотор
        unsigned char Motor_2_CH = 1;

        //Скорость мотора: > 0 - вверх (наматывает нитку), < 0 - вниз, 0 - стоп
        int Speed;
        //Сигнал кнопки и датчиков
        unsigned char Stand_By;
        unsigned char Top;                      //Place_2_1
        unsigned char Bottom;                   //Place_2_3

        Stand_By = 0;
        Top = 0;
        Bottom = 0;
        Speed = 0;

        //---- 1. Ждём нажатия кнопки Stand_by ----------------------------------
        printf("Ожидание нажатия кнопки Stand_by...\n");
        while(Stand_By == 0)
        {
                Get5050(_5050_1, Stand_by_CH, ABit, &Stand_By);
                ADAMdelay(50);
        }
        printf("Кнопка нажата. Поднимаю груз...\n");

        //---- 2. Запускаю второй мотор: груз идёт ВВЕРХ -------------------------
        Speed = 60;
        Set5024(&Speed, Motor_2_CH, AByte);

        //---- 3. Жду, пока груз дойдёт до верхнего датчика Place_2_1 ------------
        while(Top == 0)
        {
                Get5050(_5050_1, Place_2_1_CH, ABit, &Top);
                ADAMdelay(20);
        }

        //Дошёл - останавливаю мотор и разворачиваю его в другую сторону
        Speed = 0;
        Set5024(&Speed, Motor_2_CH, AByte);
        ADAMdelay(200);                         //дать грузу остановиться

        printf("Груз наверху (Place_2_1). Опускаю вниз...\n");
        Speed = -60;                            //противоположное направление
        Set5024(&Speed, Motor_2_CH, AByte);

        //---- 4. Жду нижний датчик Place_2_3 и останавливаюсь -------------------
        while(Bottom == 0)
        {
                Get5050(_5050_0, Place_2_3_CH, ABit, &Bottom);
                ADAMdelay(20);
        }

        Speed = 0;
        Set5024(&Speed, Motor_2_CH, AByte);
        printf("Груз внизу (Place_2_3). Мотор остановлен. Программа завершена.\n");
}
